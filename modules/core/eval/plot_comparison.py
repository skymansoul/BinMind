#!/usr/bin/env python3
# coding: utf-8
"""
对比实验可视化 — matplotlib 柱状图 (检出率 vs 误报率, 含加壳/未加壳分组)
与 LaTeX 对比表格 (全指标). 读取 run_benchmark.py 的 tool_comparison.json.
"""

import json, os, sys
from typing import Any, Dict, List, Optional, Tuple

import matplotlib
matplotlib.use('Agg')  # 无头模式
import matplotlib.pyplot as plt
import numpy as np

_TOOL_COLORS = {
    'BinMind': '#1f77b4',
    'Angr': '#ff7f0e',
    'QEMU': '#2ca02c',
    'Ghidra': '#d62728',
}
_TOOL_HATCH = {'BinMind': '', 'Angr': '//', 'QEMU': '..', 'Ghidra': 'xx'}


def _tools_in(comp: Dict) -> List[str]:
    tools = [t for t in comp if comp[t].get('available', True)]
    if 'BinMind' in tools:
        tools.remove('BinMind')
        tools = ['BinMind'] + tools
    return tools


def plot_grouped(comp: Dict, output_path: str,
                 figsize: Tuple[int, int] = (14, 6), dpi: int = 150):
    """按加壳/未加壳分组绘制 Precision/Recall/F1/FP-rate 柱状图."""
    groups = [('Unpacked', 'unpacked'), ('Packed', 'packed')]
    metrics = ['precision', 'recall', 'f1', 'fp_rate']
    titles = ['Precision (%)', 'Recall (%)', 'F1 Score', 'FP Rate (%)']

    fig, axes = plt.subplots(1, 4, figsize=figsize, dpi=dpi)
    for ax, (gname, gkey), mtitle, met in zip(axes, groups, titles, metrics):
        g = comp.get(gkey, {})
        tools = _tools_in(g)
        if not tools:
            ax.set_title(f'{gname}: no data')
            continue
        x = np.arange(len(tools))
        vals = [g[t].get(met, 0) * 100 for t in tools]
        bars = ax.bar(x, vals, 0.6, color=[_TOOL_COLORS.get(t, '#555')
                                           for t in tools],
                      edgecolor='black', linewidth=0.5,
                      hatch=[_TOOL_HATCH.get(t, '') for t in tools])
        ax.set_xticks(x)
        ax.set_xticklabels(tools, rotation=15)
        ax.set_ylabel('Rate (%)')
        ax.set_title(f'{gname} — {mtitle}')
        ax.set_ylim(0, 105)
        ax.grid(axis='y', alpha=0.3)
        for bar, v in zip(bars, vals):
            ax.text(bar.get_x() + bar.get_width() / 2., v + 1,
                    f'{v:.1f}', ha='center', va='bottom', fontsize=8)
    plt.tight_layout()
    plt.savefig(output_path, dpi=dpi, bbox_inches='tight')
    plt.close()
    print(f'Chart saved: {output_path}')


def plot_fp_reduction(comp: Dict, output_path: str,
                      figsize: Tuple[int, int] = (10, 5), dpi: int = 150):
    """绘制 FP Rate 对比 (unpacked vs packed) — 突出误报削减."""
    groups = [('Unpacked', 'unpacked'), ('Packed', 'packed')]
    fig, ax = plt.subplots(figsize=figsize, dpi=dpi)
    width = 0.35
    for i, (gname, gkey) in enumerate(groups):
        g = comp.get(gkey, {})
        tools = _tools_in(g)
        x = np.arange(len(tools)) + (i - 0.5) * width
        vals = [g[t].get('fp_rate', 0) * 100 for t in tools]
        ax.bar(x, vals, width, label=gname,
               color=['#1f77b4', '#ff7f0e'][i], edgecolor='black', linewidth=0.5)
    ax.set_xticks(np.arange(len(_tools_in(comp.get('all', {})))))
    ax.set_xticklabels(_tools_in(comp.get('all', {})), rotation=0)
    ax.set_ylabel('False Positive Rate (%)')
    ax.set_title('False Positive Rate by Tool (Packed vs Unpacked)')
    ax.legend()
    ax.set_ylim(0, 105)
    ax.grid(axis='y', alpha=0.3)
    plt.tight_layout()
    plt.savefig(output_path, dpi=dpi, bbox_inches='tight')
    plt.close()
    print(f'Chart saved: {output_path}')


def generate_latex_table(comp: Dict, output_path: str = 'result_table.tex',
                         caption: str = 'Multi-Tool Heap Overflow Detection '
                         'Comparison (BinMind vs. Angr)',
                         label: str = 'tab:tool_comparison'):
    """生成 LaTeX 对比表格 (unpacked + packed + all, 全指标)."""
    lines = [
        '% Auto-generated by plot_comparison.py from tool_comparison.json',
        '\\begin{table}[htbp]',
        '  \\centering',
        '  \\small',
        f'  \\caption{{{caption}}}',
        f'  \\label{{{label}}}',
        '  \\begin{tabular}{llcccccc}',
        '    \\toprule',
        '    \\textbf{Group} & \\textbf{Tool} & \\textbf{TP} & '
        '\\textbf{FP} & \\textbf{Prec.} & \\textbf{Rec.} & '
        '\\textbf{F1} & \\textbf{FP Rate} \\\\',
        '    \\midrule',
    ]
    for gname, gkey in [('Unpacked', 'unpacked'), ('Packed', 'packed'),
                        ('Overall', 'all')]:
        g = comp.get(gkey, {})
        tools = _tools_in(g)
        if not tools:
            continue
        lines.append(f'    \\multicolumn{{8}}{{l}}{{\\textit{{{gname}}}}} \\\\')
        for t in tools:
            m = g[t]
            if not m.get('available', True):
                lines.append(
                    f'    {t} & - & - & - & - & - & '
                    f'N/A ({m.get("error", "unavailable")[:30]}) \\\\')
                continue
            lines.append(
                f'    {t} & {m["tp"]} & {m["fp"]} & '
                f'{m["precision"]:.1%} & {m["recall"]:.1%} & '
                f'{m["f1"]:.3f} & {m["fp_rate"]:.1%} \\\\')
        lines.append('    \\midrule')

    lines.extend([
        '    \\bottomrule',
        '  \\end{tabular}',
        '\\end{table}',
    ])
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))
    print(f'LaTeX table saved: {output_path}')


if __name__ == '__main__':
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument('comparison_json', help='tool_comparison.json 路径')
    ap.add_argument('--output-dir', default='.')
    ap.add_argument('--prefix', default='')
    args = ap.parse_args()

    with open(args.comparison_json, 'r', encoding='utf-8') as f:
        comp = json.load(f)
    prefix = args.prefix + '_' if args.prefix else ''
    out = args.output_dir
    os.makedirs(out, exist_ok=True)
    plot_grouped(comp, os.path.join(out, f'{prefix}grouped_comparison.png'))
    plot_fp_reduction(comp, os.path.join(out, f'{prefix}fp_reduction.png'))
    generate_latex_table(comp, os.path.join(out, f'{prefix}result_table.tex'))
