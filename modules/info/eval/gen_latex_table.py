#!/usr/bin/env python
# coding: utf-8
# eval/gen_latex_table.py — 对比实验 LaTeX 表格生成器
# 读取 benchmark_v2.csv, 输出 eval/result_table.tex (booktabs 格式)。
# 跳过 skip=1 的行; 每个 (工具, 分组) 一行, 含全部指标。
# 用法: python eval/gen_latex_table.py

import csv
import json
from collections import defaultdict
from pathlib import Path

_EVAL = Path(__file__).parent
_CSV = _EVAL / "benchmark_v2.csv"
_TEX = _EVAL / "result_table.tex"
_TP = _EVAL.parent / "tests" / "heap_fp_benchmark"

GROUP_LABEL = {"unpacked": "Unpacked", "packed": "Packed"}


def _load():
    truth = {}
    for d in _TP.iterdir():
        t = d / "truth.json"
        if t.exists():
            truth[d.name] = json.loads(t.read_text(encoding="utf-8"))[
                "expect_overflow"]
    rows = list(csv.DictReader(open(_CSV, encoding="utf-8")))
    agg = defaultdict(lambda: defaultdict(lambda: [0, 0, 0, 0, 0.0, 0.0]))
    for r in rows:
        if r["sample_id"] not in truth or r.get("skip") == "1":
            continue
        expect = truth[r["sample_id"]]
        det = int(r["detected"])
        s = agg[r["tool"]][r["group"]]
        if expect and det:
            s[0] += 1
        elif expect:
            s[2] += 1
        elif det:
            s[1] += 1
        else:
            s[3] += 1
        s[4] += float(r["elapsed_s"])
        s[5] += float(r["peak_memory_mb"])
    return agg


def main():
    agg = _load()
    lines = []
    lines.append("% Auto-generated by python eval/gen_latex_table.py -- do not edit")
    lines.append("\\begin{table}[t]")
    lines.append("\\centering")
    lines.append("\\caption{Heap-Overflow Detection Comparison on 30 Samples "
                 "(15 vulnerable / 15 safe). "
                 "Packed variants have import table stripped to simulate packing.}")
    lines.append("\\label{tab:heap_comparison_v2}")
    lines.append("\\small")
    lines.append("\\begin{tabular}{l l r r r r r r r r r}")
    lines.append("\\toprule")
    lines.append("Tool & Group & TP & FP & FN & TN & Recall\\% & FPR\\% "
                 "& Prec.\\% & F1\\% & Time(s) \\\\")
    lines.append("\\midrule")
    for tool in sorted(agg):
        for group in sorted(agg[tool]):
            tp, fp, fn, tn, tt, mm = agg[tool][group]
            rec = tp / (tp + fn) * 100 if (tp + fn) else 0.0
            fpr = fp / (fp + tn) * 100 if (fp + tn) else 0.0
            prec = tp / (tp + fp) * 100 if (tp + fp) else 0.0
            f1 = (2 * prec * rec / (prec + rec)) if (prec + rec) else 0.0
            time_avg = tt / max((tp + fp + fn + tn), 1)
            lines.append(
                f"{tool} & {GROUP_LABEL.get(group, group)} & {tp} & {fp} & "
                f"{fn} & {tn} & {rec:.1f} & {fpr:.1f} & {prec:.1f} & "
                f"{f1:.1f} & {time_avg:.2f} \\\\")
    lines.append("\\midrule")
    lines.append("\\multicolumn{11}{l}{\\footnotesize "
                 "FC-VRA-v3 is source-based and thus packing-robust; "
                 "Angr/Ghidra/QEMU run on binaries. QEMU/Ghidra unavailable in "
                 "this environment are omitted.}}\\\\")
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("\\end{table}")

    _TEX.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"saved: {_TEX}")


if __name__ == "__main__":
    main()
