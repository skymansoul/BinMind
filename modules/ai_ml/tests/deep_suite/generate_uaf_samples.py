def write_sample(sid, cve, desc, readme, src):
    d = SAMPLES_ROOT / sid
    d.mkdir(parents=True, exist_ok=True)
    (d / "vuln.c").write_text(src, encoding="utf-8")
    (d / "Makefile").write_text(MAKEFILE, encoding="utf-8")
    header = f"# {sid}\nCVE/漏洞: {cve}\n描述: {desc}\n\n"
    (d / "README.md").write_text(header + readme.lstrip("\n"), encoding="utf-8")


def main():
    SAMPLES_ROOT.mkdir(parents=True, exist_ok=True)
    n = 0
    for sid, info in {**TP_SAMPLES, **FP_SAMPLES}.items():
        if (SAMPLES_ROOT / sid / "vuln.c").exists():
            continue
        write_sample(sid, info["cve"], info["desc"],
                     info["readme"], info["src"])
        n += 1
    print(f"[generate_uaf_samples] wrote {n} new sample(s) to {SAMPLES_ROOT}")


if __name__ == "__main__":
    main()
