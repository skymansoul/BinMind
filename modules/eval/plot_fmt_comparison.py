"""
格式化字符串对比可视化 — 检出率/误报率柱状图 + LaTeX 表.

读取 benchmark_fmt.csv 与 summary, 生成:
  1. 检出率/误报率分组柱状图 (按工具)
  2. result_table_fmt.tex — LaTeX 对比表
外部工具不可用时对应柱置灰.
"""

import csv
import json
import sys
from pathlib import Path
from typing import Dict, List

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np

BASE = Path(__file__).resolve().parent.parent
RESULTS = BASE / 'results'

TOOL_LABELS = {
    'BinMind-FMT': 'BinMind-FMT (ours)',
    'angr': 'Angr (symbolic)',
    'qemu': 'QEMU/Unicorn (dynamic)',
    'ghidra': 'Ghidra (pattern)',
}


def load_rows(csv_path: Path) -> List[Dict]:
    with open(csv_path, newline='', encoding='utf-8') as f:
        return list(csv.DictReader(f))


def load_summary() -> Dict:
    p = RESULTS / 'benchmark_fmt_summary.json'
    if p.exists():
        return json.loads(p.read_text(encoding='utf-8'))
    return {}


def plot_comparison(rows: List[Dict], out_png: Path) -> None:
    tools = ['BinMind-FMT', 'angr', 'qemu', 'ghidra']
    labels = [TOOL_LABELS.get(t, t) for t in tools]
    recall, fpr = [], []
    avail_flags = []
    for t in tools:
        trows = [r for r in rows if r['tool'] == t
                 and r['verdict'] != 'UNAVAILABLE']
        avail_flags.append(len(trows) > 0)
        if not trows:
            recall.append(0.0)
            fpr.append(0.0)
            continue
        vuln = [r for r in trows if r['ground_truth'] == 'VULN']
        safe = [r for r in trows if r['ground_truth'] == 'SAFE']
        tp = sum(1 for r in vuln if r['verdict'] == 'TP')
        fp = sum(1 for r in safe if r['verdict'] == 'FP')
        recall.append(tp / len(vuln) if vuln else 0.0)
        fpr.append(fp / len(safe) if safe else 0.0)

    x = np.arange(len(tools))
    w = 0.35
    fig, ax = plt.subplots(figsize=(10, 5))
    b1 = ax.bar(x - w / 2, recall, w, label='Recall', color='#2e86ab')
    b2 = ax.bar(x + w / 2, fpr, w, label='False Positive Rate',
                color='#e07a5f')
    for i, (b, a) in enumerate(zip(b1, avail_flags)):
        if not a:
            b.set_color('#cccccc')
    for i, (b, a) in enumerate(zip(b2, avail_flags)):
        if not a:
            b.set_color('#dddddd')
    ax.set_xticks(x)
    ax.set_xticklabels(labels, rotation=15)
    ax.set_ylim(0, 1.05)
    ax.set_ylabel('rate')
    ax.set_title('Format string detection: recall vs false positive rate')
    ax.legend()
    ax.grid(axis='y', alpha=0.3)
    fig.tight_layout()
    fig.savefig(out_png, dpi=150)
    plt.close(fig)


def gen_latex(summary: Dict, out_tex: Path) -> None:
    tools = ['BinMind-FMT', 'angr', 'qemu', 'ghidra']
    lines = [
        '% Auto-generated by plot_fmt_comparison.py',
        r'\begin{table}[t]',
        r'\centering',
        r'\caption{Format string detection comparison across tools.}',
        r'\label{tab:fmt_comparison}',
        r'\begin{tabular}{lcccccc}',
        r'\toprule',
        r'Tool & TP & FP & FN & TN & Recall & FPR \\',
        r'\midrule',
    ]
    for t in tools:
        s = summary.get(t, {})
        if s.get('status') == 'unavailable' or not s:
            lines.append(f'{t} & -- & -- & -- & -- & -- & -- \\\\')
            continue
        lines.append(
            f'{TOOL_LABELS.get(t, t)} & {s["tp"]} & {s["fp"]} & '
            f'{s["fn"]} & {s["tn"]} & {s["recall"]:.3f} & '
            f'{s["fpr"]:.3f} \\\\')
    lines += [
        r'\bottomrule',
        r'\end{tabular}',
        r'\end{table}',
        '',
    ]
    out_tex.parent.mkdir(parents=True, exist_ok=True)
    out_tex.write_text('\n'.join(lines), encoding='utf-8')


def main() -> int:
    csv_path = RESULTS / 'benchmark_fmt.csv'
    if not csv_path.exists():
        print(f'missing {csv_path}; run run_fmt_benchmark.py first')
        return 1
    rows = load_rows(csv_path)
    summary = load_summary()
    plot_comparison(rows, RESULTS / 'fig_fmt_comparison.png')
    gen_latex(summary, RESULTS / 'result_table_fmt.tex')
    print('figures: fig_fmt_comparison.png')
    print('latex: result_table_fmt.tex')
    return 0


if __name__ == '__main__':
    sys.exit(main())