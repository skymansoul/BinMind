"""
生成堆溢出检测对比图表 — matplotlib 柱状图 + LaTeX 表格.

对 benchmark 结果生成三组图:
  1. 检出率/误报率对比柱状图 (分组: 未加壳)
  2. 各工具在 TP/FP/TN/FN 上的堆叠柱状图
  3. 各工具平均耗时条形图

同时生成 LaTeX 对比表格代码.
"""

import json
import os
import sys
from pathlib import Path
from typing import Dict, List

EVAL_DIR = Path(__file__).parent


def load_benchmark_data(json_path: str = "") -> Dict:
    """加载 benchmark JSON 数据."""
    if not json_path:
        json_path = EVAL_DIR / "benchmark_metrics.json"
    if os.path.exists(json_path):
        with open(json_path) as f:
            return json.load(f)
    return {}


def generate_comparison_chart(data: Dict, output_png: str = "") -> str:
    """生成检出率/误报率对比柱状图."""
    try:
        import matplotlib
        matplotlib.use('Agg')
        import matplotlib.pyplot as plt
        import numpy as np
    except ImportError:
        return "matplotlib not available"

    metrics = data.get("metrics", [])
    if not metrics:
        return "no data to plot"

    tools = [m["tool"] for m in metrics]
    recall = [m["recall"] * 100 for m in metrics]
    fp_rate = [m["fp_rate"] * 100 for m in metrics]
    precision = [m["precision"] * 100 for m in metrics]

    x = np.arange(len(tools))
    width = 0.25

    fig, ax = plt.subplots(figsize=(12, 6))

    bars1 = ax.bar(x - width, recall, width, label='Recall (Detection Rate)',
                   color='#2ecc71', edgecolor='white')
    bars2 = ax.bar(x, fp_rate, width, label='False Positive Rate',
                   color='#e74c3c', edgecolor='white')
    bars3 = ax.bar(x + width, precision, width, label='Precision',
                   color='#3498db', edgecolor='white')

    ax.set_ylabel('Rate (%)', fontsize=12)
    ax.set_title('Heap Overflow Detection: Multi-Tool Comparison\n'
                 '(17 CVE-based samples)',
                 fontsize=14, fontweight='bold')
    ax.set_xticks(x)
    ax.set_xticklabels(tools, fontsize=11)
    ax.legend(fontsize=10)
    ax.set_ylim(0, 105)
    ax.grid(axis='y', alpha=0.3)

    # 在柱上标注数值
    for bars in [bars1, bars2, bars3]:
        for bar in bars:
            height = bar.get_height()
            if height > 0:
                ax.annotate(f'{height:.0f}%',
                           xy=(bar.get_x() + bar.get_width() / 2, height),
                           xytext=(0, 3), textcoords="offset points",
                           ha='center', va='bottom', fontsize=8)

    plt.tight_layout()

    if not output_png:
        output_png = str(EVAL_DIR / "detection_comparison.png")
    plt.savefig(output_png, dpi=150)
    plt.close()
    return f"Chart saved to {output_png}"


def generate_confusion_matrix_chart(data: Dict, output_png: str = "") -> str:
    """生成 TP/FP/TN/FN 堆叠柱状图."""
    try:
        import matplotlib
        matplotlib.use('Agg')
        import matplotlib.pyplot as plt
        import numpy as np
    except ImportError:
        return "matplotlib not available"

    metrics = data.get("metrics", [])
    if not metrics:
        return "no data"

    tools = [m["tool"] for m in metrics]
    tp_vals = [m["true_positive"] for m in metrics]
    fp_vals = [m["false_positive"] for m in metrics]
    tn_vals = [m["true_negative"] for m in metrics]
    fn_vals = [m["false_negative"] for m in metrics]

    x = np.arange(len(tools))
    width = 0.6

    fig, ax = plt.subplots(figsize=(12, 6))

    ax.bar(x, tp_vals, width, label='True Positive', color='#27ae60')
    ax.bar(x, tn_vals, width, bottom=tp_vals, label='True Negative',
           color='#2980b9')
    ax.bar(x, fp_vals, width, bottom=[t + tn for t, tn in zip(tp_vals, tn_vals)],
           label='False Positive', color='#e74c3c')
    ax.bar(x, fn_vals, width,
           bottom=[t + tn + fp for t, tn, fp in zip(tp_vals, tn_vals, fp_vals)],
           label='False Negative', color='#f39c12')

    ax.set_ylabel('Number of Samples', fontsize=12)
    ax.set_title('Detection Confusion Matrix by Tool\n(17 Heap Overflow Samples)',
                 fontsize=14, fontweight='bold')
    ax.set_xticks(x)
    ax.set_xticklabels(tools, fontsize=11)
    ax.legend(fontsize=10)
    ax.set_ylim(0, max(tp_vals) + max(tn_vals) + max(fp_vals) + 5)
    ax.grid(axis='y', alpha=0.3)

    plt.tight_layout()

    if not output_png:
        output_png = str(EVAL_DIR / "confusion_matrix.png")
    plt.savefig(output_png, dpi=150)
    plt.close()
    return f"Chart saved to {output_png}"


def generate_latex_table(data: Dict) -> str:
    """生成 LaTeX 对比表格."""
    metrics = data.get("metrics", [])

    lines = [
        "% Heap Overflow Detection — Multi-Tool Comparison",
        "% Generated by plot_comparison_enhanced.py",
        "",
        "\\begin{table}[htbp]",
        "  \\centering",
        "  \\caption{Heap Overflow Detection Performance Comparison}",
        "  \\label{tab:heap-overflow-comparison}",
        "  \\small",
        "  \\begin{tabular}{lcccccc}",
        "    \\toprule",
        "    \\textbf{Tool} & \\textbf{Samples} & \\textbf{Recall} & "
        "\\textbf{FP Rate} & \\textbf{Precision} & "
        "\\textbf{Avg Time (ms)} & \\textbf{FP Reduction} \\\\",
        "    \\midrule",
    ]

    # 找 BinMind 作为参考
    binmind_recall = None
    for m in metrics:
        if "BinMind" in m["tool"]:
            binmind_recall = m["recall"]

    for m in metrics:
        tool = m["tool"]
        samples = m["samples"]
        recall = f"{m['recall']:.1%}"
        fp_rate = f"{m['fp_rate']:.1%}"
        precision = f"{m['precision']:.1%}"
        avg_time = f"{m['avg_time_ms']:.0f}"
        fp_reduction = "-"
        if "BinMind" in tool:
            fp_reduction = "Baseline (\\textbf{our method})"
        else:
            # 计算相对于基线 Angr 的 FP 减少
            for ref in metrics:
                if "Angr" in ref["tool"]:
                    if ref["fp_rate"] > 0 and m["fp_rate"] > 0:
                        ratio = ref["fp_rate"] / m["fp_rate"]
                        if ratio > 1:
                            fp_reduction = f"${ratio:.1f}\\times$ better"
                        else:
                            fp_reduction = f"${1/ratio:.1f}\\times$ worse"
                    break

        lines.append(
            f"    {tool:12s} & {samples} & {recall} & {fp_rate} & "
            f"{precision} & {avg_time} & {fp_reduction} \\\\"
        )

    lines.extend([
        "    \\bottomrule",
        "  \\end{tabular}",
        "",
        "  \\vspace{4pt}",
        "  \\footnotesize{",
        "  \\textbf{Note:} BinMind uses 5-phase path-sensitive strided interval",
        "  analysis with allocator semantics (Phase 0--4). Angr and Ghidra run",
        "  without heap-specific FP reduction. QEMU/GT provides ground truth",
        "  via runtime memory operation logging.}",
        "\\end{table}",
    ])

    return "\n".join(lines)


def main():
    data = load_benchmark_data()
    if not data:
        print("No benchmark data found. Run run_benchmark_enhanced.py first.")
        return 1

    # 生成图表
    r1 = generate_comparison_chart(data)
    print(r1)

    r2 = generate_confusion_matrix_chart(data)
    print(r2)

    # 生成 LaTeX 表格
    latex = generate_latex_table(data)
    latex_path = EVAL_DIR / "result_table_enhanced.tex"
    with open(latex_path, "w") as f:
        f.write(latex)
    print(f"LaTeX table written to {latex_path}")

    print(f"\n{latex}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
