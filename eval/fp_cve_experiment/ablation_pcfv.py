"""PCFV 消融实验 — 各证明规则的独立贡献 (FP 过滤 / 召回保持).

用法: python eval/fp_cve_experiment/ablation_pcfv.py [--exe vuln.exe]
输出: results/ablation_pcfv.csv, ablation_pcfv_table.tex, ablation_pcfv.png
配置:
  full         全规则 (生产配置)
  no_guard     禁用守卫支配规则
  no_minchunk  禁用最小块规则 (安全侧+溢出侧)
  no_padding   禁用分配器padding排除
  no_loop      禁用循环规则 (界内安全+累积溢出)
  no_const     禁用常量证明 (const_bounded + padding)
  bound_only   全部禁用 (等价纯边界检查基线)
"""
import argparse
import csv
import os

from _common import HERE as _HERE, list_samples, setup_paths, try_import
setup_paths(with_format=False)
from pcfv import analyze_heap_pcfv
CORPUS = os.path.join(_HERE, 'corpus')
RESULTS = os.path.join(_HERE, 'results')
_ALL_KEYS = ('guard', 'minchunk', 'padding', 'loop', 'const_bounded',
             'unbounded_copy', 'realloc')
CONFIGS = {
    'full': {},
    'no_guard': {'guard': False},
    'no_minchunk': {'minchunk': False},
    'no_padding': {'padding': False},
    'no_loop': {'loop': False},
    'no_const': {'const_bounded': False, 'padding': False},
    'bound_only': {k: False for k in _ALL_KEYS},
}
def run_config(cfg: dict, exe_name: str) -> dict:
    tp = fn = fp = tn = 0
    for d, truth in list_samples(CORPUS):
        exe = os.path.join(d, exe_name)
        if not os.path.exists(exe):
            continue
        r = analyze_heap_pcfv(exe, rule_enabled=cfg or None)
        kept = r.confirmed + r.likely + r.uncertain > 0
        if truth['expected_vuln']:
            if kept:
                tp += 1
            else:
                fn += 1
        elif kept:
            fp += 1
        else:
            tn += 1
    prec = tp / (tp + fp) if tp + fp else 0.0
    rec = tp / (tp + fn) if tp + fn else 0.0
    f1 = 2 * prec * rec / (prec + rec) if prec + rec else 0.0
    return {'tp': tp, 'fn': fn, 'fp': fp, 'tn': tn,
            'precision': round(prec, 4), 'recall': round(rec, 4),
            'f1': round(f1, 4)}
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--exe', default='vuln.exe')
    args = ap.parse_args()
    rows = []
    for name, cfg in CONFIGS.items():
        m = run_config(cfg, args.exe)
        rows.append({'config': name, **m})
        print('%-12s TP=%2d FN=%2d FP=%2d TN=%2d | P=%.4f R=%.4f F1=%.4f'
              % (name, m['tp'], m['fn'], m['fp'], m['tn'], m['precision'],
                 m['recall'], m['f1']))
    csv_path = os.path.join(RESULTS, 'ablation_pcfv.csv')
    with open(csv_path, 'w', newline='', encoding='utf-8') as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    print('saved ->', csv_path)
    # LaTeX 表格
    tex = ['%% Auto-generated by ablation_pcfv.py',
           '\\begin{table}[htbp]', '\\centering',
           '\\caption{PCFV ablation: per-rule contribution '
           '(%s variant, 15 TP + 15 safe).}' % args.exe,
           '\\label{tab:ablation-pcfv}', '\\small',
           '\\begin{tabular}{lccccccc}', '\\toprule',
           'Config & TP & FP & FN & TN & Precision & Recall & F1 \\\\',
           '\\midrule']
    label_map = {'full': '\\textbf{full (all rules)}',
                 'no_guard': 'w/o guard-dominance',
                 'no_minchunk': 'w/o min-chunk',
                 'no_padding': 'w/o allocator padding',
                 'no_loop': 'w/o loop rules',
                 'no_const': 'w/o const proofs',
                 'bound_only': 'bound-check only'}
    for r in rows:
        tex.append('%s & %d & %d & %d & %d & %.3f & %.3f & %.3f \\\\' % (
            label_map.get(r['config'], r['config']), r['tp'], r['fp'],
            r['fn'], r['tn'], r['precision'], r['recall'], r['f1']))
    tex += ['\\bottomrule', '\\end{tabular}', '\\end{table}']
    tex_path = os.path.join(RESULTS, 'ablation_pcfv_table.tex')
    with open(tex_path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(tex))
    print('saved ->', tex_path)
    # 柱状图 (F1 对比)
    matplotlib = try_import('matplotlib')
    if matplotlib is not None:
        matplotlib.use('Agg')
        import matplotlib.pyplot as plt
        names = [r['config'] for r in rows]
        f1s = [r['f1'] for r in rows]
        fps = [r['fp'] for r in rows]
        fig, ax1 = plt.subplots(figsize=(9, 4.5))
        x = list(range(len(names)))
        b1 = ax1.bar([i - 0.2 for i in x], f1s, 0.4, label='F1',
                     color='#4c72b0')
        ax1.set_ylabel('F1')
        ax1.set_ylim(0, 1.1)
        ax2 = ax1.twinx()
        b2 = ax2.bar([i + 0.2 for i in x], fps, 0.4, label='FP count',
                     color='#dd8452')
        ax2.set_ylabel('FP count')
        ax2.set_ylim(0, 16)
        ax1.set_xticks(x)
        ax1.set_xticklabels(names, rotation=15)
        ax1.legend(loc='upper left')
        ax2.legend(loc='upper right')
        ax1.grid(axis='y', alpha=0.3)
        fig.suptitle('PCFV Ablation (%s)' % args.exe)
        fig.tight_layout()
        png = os.path.join(RESULTS, 'ablation_pcfv.png')
        fig.savefig(png, dpi=150)
        plt.close(fig)
        print('saved ->', png)
if __name__ == '__main__':
    main()
