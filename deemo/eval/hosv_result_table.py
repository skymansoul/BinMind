# coding: utf-8
"""
生成堆溢出检测对比 LaTeX 表 — 从 benchmark JSON 读取交叉指标.
输出: eval/hosv_result_table.tex
"""

import json
import os

BASE = os.path.dirname(os.path.abspath(__file__))


def main():
    with open(os.path.join(BASE, "hosv_benchmark_results.json"),
              "r", encoding="utf-8") as f:
        data = json.load(f)
    cross = data["cross"]
    rows = []
    for c in cross:
        rows.append("    %s & %d & %d & %d & %d & %.3f & %.3f & %.3f & %.3f & %.2f \\\\" % (
            c["tool"], c["tp"], c["fp"], c["fn"], c["tn"],
            c["precision"], c["recall"], c["f1"],
            c["total_time_s"], c["peak_mb"]))
    latex = """%% Auto-generated by hosv_result_table.py
%% Heap-overflow detection comparison on 18 samples (12 VULN + 6 SAFE)
\\begin{table}[t]
\\centering
\\caption{HOSV-Ext vs. Baseline --- Heap Overflow Detection (18 samples)}
\\label{tab:hosv-comparison}
\\begin{tabular}{lccccccccc}
\\toprule
Tool & TP & FP & FN & TN & Prec. & Recall & F1 & Time(s) & Peak(MB) \\\\
\\midrule
%s
\\bottomrule
\\end{tabular}
\\end{table}
""" % "\n".join(rows)
    out = os.path.join(BASE, "hosv_result_table.tex")
    with open(out, "w", encoding="utf-8") as f:
        f.write(latex)
    print("saved:", out)


if __name__ == "__main__":
    main()
