"""LaTeX 对比表格生成 — 从基准CSV输出 result_table.tex.

创建: 2026-05-01
用法: python eval/fp_cve_experiment/gen_latex_table.py [--exe vuln.exe]
输出: eval/fp_cve_experiment/results/result_table_O0.tex 等
"""
import argparse
import csv
import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
RESULTS = os.path.join(_HERE, 'results')

TOOL_ORDER = ['pcfv', 'baseline', 'angr', 'ghidra', 'asan']
TOOL_LABEL = {'pcfv': '\\textbf{PCFV (Ours)}',
              'baseline': 'DP-TVRA baseline',
              'angr': 'Angr (reachable sites)',
              'ghidra': 'Ghidra (heuristic)',
              'asan': 'Runtime shim (GT)'}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--exe', default='vuln.exe')
    args = ap.parse_args()
    label = 'O0' if args.exe == 'vuln.exe' else 'O2'

    rows = list(csv.DictReader(open(
        os.path.join(RESULTS, 'benchmark_%s.csv' % label.lower()),
        encoding='utf-8')))
    total = sum(1 for r in rows if r['tool'] == 'pcfv')
    vuln_n = sum(1 for r in rows if r['tool'] == 'pcfv'
                 and r['expected_vuln'] == 'True')
    safe_n = total - vuln_n

    lines = []
    lines.append('%% Auto-generated by gen_latex_table.py (%s variant)' % label)
    lines.append('\\begin{table}[htbp]')
    lines.append('\\centering')
    lines.append('\\caption{Heap-overflow detection comparison on the corpus '
                 '(compiled with %s; %d vulnerable + %d safe samples). '
                 '\\textbf{PCFV} keeps recall of the baseline family while '
                 'reducing false positives to zero.}'
                 % (label, vuln_n, safe_n))
    lines.append('\\label{tab:heap-comparison-%s}' % label.lower())
    lines.append('\\small')
    lines.append('\\begin{tabular}{lcccccc}')
    lines.append('\\toprule')
    lines.append('Tool & TP & FP & FN & Precision & Recall & F1 \\\\')
    lines.append('\\midrule')
    for tool in TOOL_ORDER:
        tr = [r for r in rows if r['tool'] == tool]
        if not tr:
            continue
        tp = sum(1 for r in tr if r['expected_vuln'] == 'True'
                 and r['fn_count'] == '0')
        fn = sum(int(r['fn_count']) for r in tr)
        fp = sum(int(r['fp_count']) for r in tr)
        prec = tp / (tp + fp) if tp + fp else 0.0
        rec = tp / (tp + fn) if tp + fn else 0.0
        f1 = 2 * prec * rec / (prec + rec) if prec + rec else 0.0
        lines.append('%s & %d & %d & %d & %.3f & %.3f & %.3f \\\\'
                     % (TOOL_LABEL.get(tool, tool), tp, fp, fn,
                        prec, rec, f1))
    lines.append('\\bottomrule')
    lines.append('\\end{tabular}')
    lines.append('\\end{table}')
    text = '\n'.join(lines)
    out = os.path.join(RESULTS, 'result_table_%s.tex' % label)
    with open(out, 'w', encoding='utf-8') as f:
        f.write(text)
    print('saved ->', out)


if __name__ == '__main__':
    main()
