def language() -> str:
    return LANGUAGE if LANGUAGE in ('zh', 'en') else 'zh'


def is_zh() -> bool:
    return language() == 'zh'


def tr(key: str, **kwargs) -> str:
    text = _TRANSLATIONS.get(language(), _TRANSLATIONS['zh']).get(key)
    if text is None:
        text = _TRANSLATIONS['en'].get(key, key)
    return text.format(**kwargs) if kwargs else text
