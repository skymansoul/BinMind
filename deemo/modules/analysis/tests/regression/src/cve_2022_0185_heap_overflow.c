// 安全对照: malloc(576) + memcpy(576/2) → 不溢出
void fs_context_safe() {
    char *buf = (char *)malloc(576);
    if (!buf) return;
    memcpy(buf, "safe data here", 14);
    printf("fs_context_safe: %s\n", buf);
    free(buf);
}

