#!/usr/bin/env python
# coding: utf-8
# eval/gen_multi_table.py — 多类型误报回归 LaTeX 表格生成器
# 读取 tests/multi_fp_regression/results/summary_multi.json → multi_fp_table.tex
# 用法: python eval/gen_multi_table.py

import json
from pathlib import Path

_EVAL = Path(__file__).parent
_SUMMARY = (_EVAL.parent / "tests" / "multi_fp_regression" / "results"
            / "summary_multi.json")
_TEX = _EVAL / "multi_fp_table.tex"

TYPE_LABEL = {"heap": "Heap Overflow", "uaf": "Use-After-Free",
              "fmt": "Format String"}


def main():
    data = json.loads(_SUMMARY.read_text(encoding="utf-8"))
    lines = ["% Auto-generated by python eval/gen_multi_table.py -- do not edit",
             "\\begin{table}[t]", "\\centering",
             "\\caption{FP-Reduction across three vulnerability types. "
             "Each row is a 30-sample benchmark (15 vulnerable / 15 safe). "
             "FC*-v3 detectors are this work.}",
             "\\label{tab:multi_fp}",
             "\\small",
             "\\begin{tabular}{l l r r r r r r r}",
             "\\toprule",
             "Vuln. Type & Tool & TP & FP & FN & TN & Recall\\% & FPR\\% & F1\\% \\\\",
             "\\midrule"]
    for vtype in ["heap", "uaf", "fmt"]:
        rows = [r for r in data if r["type"] == vtype]
        rows.sort(key=lambda r: r["f1_pct"], reverse=True)
        for i, r in enumerate(rows):
            label = TYPE_LABEL.get(vtype, vtype) if i == 0 else ""
            lines.append(f"{label} & {r['tool']} & {r['TP']} & {r['FP']} & "
                         f"{r['FN']} & {r['TN']} & {r['recall_pct']} & "
                         f"{r['fpr_pct']} & {r['f1_pct']} \\\\")
        if vtype != "fmt":
            lines.append("\\midrule")
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("\\end{table}")
    _TEX.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"saved: {_TEX}")


if __name__ == "__main__":
    main()
