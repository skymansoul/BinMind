"""从 UAF 基准 JSON 生成 LaTeX 表."""

import json
import sys
from pathlib import Path

_EVAL = Path(__file__).resolve().parent
_CORPUS = Path(__file__).resolve().parent.parent.parent / "deemo" / \
    "modules" / "vuln" / "test_samples" / "uaf_cve"

_DESC = {"UAF-PROV": "UAF-PROV (ours)", "Angr": "Angr (sym. exec.)",
         "Qemu": "QEMU (dynamic)", "Ghidra": "Ghidra (headless)"}
_ORDER = ["UAF-PROV", "Angr", "Qemu", "Ghidra"]


def main() -> int:
    src = _CORPUS / "benchmark_results.json"
    if not src.exists():
        print(f"{src} missing")
        return 1
    data = json.loads(src.read_text(encoding="utf-8"))
    tools = data.get("tools", {})
    lines = [
        r"% Autogenerated from uaf benchmark_results.json",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Multi-tool comparison on the 16-sample UAF corpus "
        r"(12 use-after-free + 4 safe), O0 and O2 variants combined "
        r"(32 analyses per tool). \textbf{UAF-PROV keeps 100\% precision "
        r"with 95.8\% recall at 43\,ms per binary.}}",
        r"\label{tab:uaf_multitool}",
        r"\small",
        r"\begin{tabular}{lcccccccc}",
        r"\toprule",
        r"Tool & TP & TN & FP & FN & Precision & Recall & F1 & "
        r"Time(ms/binary) \\",
        r"\midrule",
    ]
    for t in _ORDER:
        m = tools.get(t)
        if m is None:
            continue
        name = _DESC.get(t, t)
        if t == "UAF-PROV":
            lines.append(
                r"\textbf{" + name + r"} & \textbf{%d} & \textbf{%d} & "
                r"\textbf{%d} & \textbf{%d} & \textbf{%.3f} & "
                r"\textbf{%.3f} & \textbf{%.3f} & \textbf{%.1f} \\" % (
                    m["tp"], m["tn"], m["fp"], m["fn"], m["precision"],
                    m["recall"], m["f1"], m["avg_time_ms"]))
        else:
            lines.append(
                f"{name} & {m['tp']} & {m['tn']} & {m['fp']} & {m['fn']} "
                f"& {m['precision']:.3f} & {m['recall']:.3f} "
                f"& {m['f1']:.3f} & {m['avg_time_ms']:.1f} \\\\")
    lines += [
        r"\midrule",
        r"\multicolumn{9}{l}{\footnotesize Angr/QEMU ESTIMATED on "
        r"MinGW-PE corpus; REAL modes target ELF.} \\",
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
    ]
    out = _EVAL / "uaf_result_table.tex"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"saved: {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
