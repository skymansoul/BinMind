"""对比可视化 — 从 benchmark_results.json 生成图表与 LaTeX 表格.

图表:
  comparison_bar.png   各工具 检出率(recall) 与 误报率(FPR) 柱状图
  comparison_fpr.png   良性与漏洞分组下 各工具 误报数对比
  comparison_strip.png 加壳(去符号)分组 与 未加壳 的 F1 对比

LaTeX:
  result_table.tex     全指标对比表格 (TP/FP/FN/TN/Precision/Recall/F1/FPR)

注: 本机无 UPX, 加壳分组以 objcopy 去符号+去调试信息作为
混淆加固的诚实代理 (run_benchmark --strip 生成).
"""

import json
import os
import sys

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

EVAL_DIR = os.path.dirname(os.path.abspath(__file__))
RESULTS = os.path.join(EVAL_DIR, "benchmark_results.json")

TOOL_LABELS = {
    "binmind_absint": "BinMind-absint\n(baseline)",
    "binmind_giva": "BinMind-GIVA\n(PG-WBV)",
    "binmind_uaf_fpmin": "BinMind-UAF\n(FPMIN)",
    "binmind_fmt_fpmin": "BinMind-FMT\n(FPMIN)",
    "binmind_intof_fpmin": "BinMind-IO\n(FPMIN)",
    "angr": "angr\n(symexec)",
    "qemu": "QEMU\n(runtime)",
    "ghidra": "Ghidra\n(headless)",
    "flawfinder": "flawfinder",
    "cppcheck": "cppcheck",
}

TOOL_COLORS = {
    "binmind_absint": "#8ca0b8",
    "binmind_giva": "#2e7d32",
    "binmind_uaf_fpmin": "#00695c",
    "binmind_fmt_fpmin": "#00838f",
    "binmind_intof_fpmin": "#0277bd",
    "angr": "#c62828",
    "qemu": "#6a1b9a",
    "ghidra": "#ef6c00",
    "flawfinder": "#5d4037",
    "cppcheck": "#455a64",
}


def load_results() -> dict:
    with open(RESULTS, encoding="utf-8") as f:
        return json.load(f)


def tool_metrics(data: dict, tool: str, group: str = "all") -> dict:
    rows = [r for r in data["rows"]
            if r["tool"] == tool
            and (group == "all" or r["group"] == group)]
    if not rows:
        return None
    tp = sum(r["tp"] for r in rows)
    fp = sum(r["fp"] for r in rows)
    fn = sum(r["fn"] for r in rows)
    tn = sum(r["tn"] for r in rows)
    prec = tp / (tp + fp) if tp + fp else 1.0
    rec = tp / (tp + fn) if tp + fn else 0.0
    f1 = 2 * prec * rec / (prec + rec) if prec + rec else 0.0
    fpr = fp / (fp + tn) if fp + tn else 0.0
    return {"tp": tp, "fp": fp, "fn": fn, "tn": tn,
            "precision": prec, "recall": rec, "f1": f1, "fp_rate": fpr}


def plot_main(data: dict):
    tools = list(TOOL_LABELS.keys())
    metrics = {t: tool_metrics(data, t) for t in tools}
    metrics = {t: m for t, m in metrics.items() if m}

    fig, axes = plt.subplots(1, 2, figsize=(14, 5.5))
    labels = [TOOL_LABELS[t] for t in metrics]
    recalls = [m["recall"] * 100 for m in metrics.values()]
    fprs = [m["fp_rate"] * 100 for m in metrics.values()]
    colors = [TOOL_COLORS[t] for t in metrics]

    ax = axes[0]
    bars = ax.bar(labels, recalls, color=colors, alpha=0.9)
    ax.set_ylabel("Detection Rate (Recall) %")
    ax.set_title("Detection Rate by Tool (41-sample corpus)")
    ax.set_ylim(0, 105)
    for bar, v in zip(bars, recalls):
        ax.text(bar.get_x() + bar.get_width() / 2, v + 1.5,
                f"{v:.0f}%", ha="center", fontsize=9)

    ax = axes[1]
    bars = ax.bar(labels, fprs, color=colors, alpha=0.9)
    ax.set_ylabel("False Positive Rate %")
    ax.set_title("False Positive Rate by Tool (benign samples)")
    ax.set_ylim(0, 105)
    for bar, v in zip(bars, fprs):
        ax.text(bar.get_x() + bar.get_width() / 2, v + 1.5,
                f"{v:.1f}%", ha="center", fontsize=9)

    for ax in axes:
        ax.tick_params(axis="x", labelsize=8)
        ax.grid(axis="y", linestyle=":", alpha=0.4)
    fig.tight_layout()
    fig.savefig(os.path.join(EVAL_DIR, "comparison_bar.png"), dpi=150)
    plt.close(fig)
    print("[OK] comparison_bar.png")


def plot_strip(data: dict):
    """加壳(去符号) vs 未加壳 F1 对比."""
    groups = [g for g in ("plain", "stripped") if g in data["group_summary"]]
    if len(groups) < 2:
        print("[!] 无 stripped 数据, 跳过 comparison_strip.png")
        return
    tools = [t for t in TOOL_LABELS if t in data["group_summary"]["plain"]]
    x = range(len(tools))
    width = 0.38
    fig, ax = plt.subplots(figsize=(11, 5))
    for gi, g in enumerate(groups):
        vals = [data["group_summary"][g].get(t, {}).get("f1", 0)
                for t in tools]
        ax.bar([i + (gi - 0.5) * width for i in x], vals, width,
               label="stripped (packed proxy)" if g == "stripped" else
                     "plain (unpacked)")
    ax.set_xticks(list(x))
    ax.set_xticklabels([TOOL_LABELS[t] for t in tools], fontsize=8)
    ax.set_ylabel("F1")
    ax.set_ylim(0, 1.1)
    ax.set_title("F1: stripped (packed proxy) vs plain")
    ax.legend()
    ax.grid(axis="y", linestyle=":", alpha=0.4)
    fig.tight_layout()
    fig.savefig(os.path.join(EVAL_DIR, "comparison_strip.png"), dpi=150)
    plt.close(fig)
    print("[OK] comparison_strip.png")


def write_latex(data: dict):
    tools = [t for t in TOOL_LABELS if tool_metrics(data, t)]
    lines = [
        "% Generated by plot_comparison.py — 多工具堆溢出检测对比",
        "% 指标: TP/FP/FN/TN, Precision, Recall, F1, FPR, 平均耗时(ms)",
        "\\begin{table}[ht]",
        "\\centering",
        "\\caption{Heap-Overflow Detection: Multi-Tool Comparison "
        "(41 samples: 22 vulnerable / 19 benign)}",
        "\\label{tab:multi-tool}",
        "\\begin{tabular}{lccccccccr}",
        "\\toprule",
        "Tool & TP & FP & FN & TN & Prec & Recall & F1 & FPR & Avg-ms \\\\",
        "\\midrule",
    ]
    for t in tools:
        m = tool_metrics(data, t)
        ms = sum(r["elapsed_ms"] for r in data["rows"]
                 if r["tool"] == t) / max(1, sum(
                     1 for r in data["rows"] if r["tool"] == t))
        name = t.replace("_", "\\_")
        lines.append(
            f"{name} & {m['tp']} & {m['fp']} & {m['fn']} & {m['tn']} & "
            f"{m['precision']:.2f} & {m['recall']:.2f} & {m['f1']:.2f} & "
            f"{m['fp_rate'] * 100:.1f}\\% & {ms:.0f} \\\\")
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
        "",
        "% 加壳(去符号)分组指标:",
    ]
    for g, gtools in data.get("group_summary", {}).items():
        lines.append(f"% [{g}] " + ", ".join(
            f"{t}: F1={m['f1']:.2f}, FPR={m['fp_rate'] * 100:.1f}\\%"
            for t, m in gtools.items()))
    tex = "\n".join(lines)
    with open(os.path.join(EVAL_DIR, "result_table.tex"), "w",
              encoding="utf-8") as f:
        f.write(tex)
    print("[OK] result_table.tex")


def main():
    if not os.path.isfile(RESULTS):
        print(f"[!] 先运行 run_benchmark.py 生成 {RESULTS}")
        return 1
    data = load_results()
    plot_main(data)
    plot_strip(data)
    write_latex(data)
    print("[*] 可视化与表格输出完成")
    return 0


if __name__ == "__main__":
    sys.exit(main())
