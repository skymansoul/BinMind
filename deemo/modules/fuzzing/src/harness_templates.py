"""
Harness templates for fuzzing target generation.

Centralises the C/C++ boilerplate used to produce LibFuzzer and AFL/AFL++
fuzz-target stubs.  The template lives in its own module so the orchestration
layer (fuzz_integration.py) stays focused on process lifecycle, crash triage,
and sandbox management -- it should not also be a code-generator warehouse.

Rationale: extracting the template string from a 47 KB integration file
eliminates the single largest block of non-logic data, makes the template
trivially reusable across other tooling, and keeps the integration module
below a reasonable line-count threshold without losing any functionality.
"""

