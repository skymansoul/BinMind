"""LaTeX 对比表格生成 — 由 benchmark_summary 的 plain 组指标生成。

输出 result_table_<class>.tex, 列: TP/FP/TN/FN/Prec/Recall/F1/FPR/耗时/内存。
用法: python eval/gen_latex_table.py [--class heap|uaf]
"""

import argparse
import json
import os
import time
from pathlib import Path

EVAL = Path(__file__).resolve().parent
ORDER = {
    'heap': ['CACBV', 'Baseline', 'Angr', 'Ghidra', 'QEMU-GT'],
    'uaf': ['LCV', 'Baseline', 'Angr', 'Ghidra', 'QEMU-GT'],
    'fmt': ['FSV', 'Baseline', 'Angr', 'Ghidra', 'QEMU-GT'],
}
CAPTION = {
    'heap': 'Multi-Tool Heap Overflow Detection Comparison',
    'uaf': 'Multi-Tool Use-After-Free Detection Comparison',
    'fmt': 'Multi-Tool Format-String Detection Comparison',
}


def _get(metrics: dict, tool: str, group: str):
    m = metrics.get(f'{tool}@{group}')
    if m:
        return m
    return metrics.get(f'{tool}@plain') or metrics.get(tool)


def write_latex(metrics: dict, path: Path, sample_class: str = 'heap') -> None:
    lines = [
        '% Auto-generated by eval/gen_latex_table.py',
        '% Generated: ' + time.strftime('%Y-%m-%d %H:%M:%S'),
        '',
        r'\begin{table}[htbp]',
        r'\centering',
        r'\caption{' + CAPTION[sample_class] +
        r' (24 samples, plain binaries)}',
        r'\label{tab:' + sample_class + r'-multi-tool}',
        r'\small',
        r'\begin{tabular}{lrrrrrrrrrr}',
        r'\toprule',
        r'\textbf{Tool} & \textbf{TP} & \textbf{FP} & \textbf{TN} & '
        r'\textbf{FN} & \textbf{Prec} & \textbf{Rec} & \textbf{F1} & '
        r'\textbf{FPR} & \textbf{ms} & \textbf{MB} \\',
        r'\midrule',
    ]
    for tool in ORDER[sample_class]:
        m = _get(metrics, tool, 'plain')
        if not m:
            lines.append(f'{tool} & -- & -- & -- & -- & -- & -- & -- & '
                         f'-- & -- & -- \\\\')
            continue
        lines.append(
            f'{tool} & {m["tp"]} & {m["fp"]} & {m["tn"]} & {m["fn"]} & '
            f'{m["precision"]*100:.1f}\\% & {m["recall"]*100:.1f}\\% & '
            f'{m["f1"]:.3f} & {m["fpr"]*100:.1f}\\% & '
            f'{m["avg_ms"]:.1f} & {m["peak_mb"]:.1f} \\\\')
    lines.extend([
        r'\bottomrule',
        r'\end{tabular}',
        r'\end{table}',
    ])
    path.write_text('\n'.join(lines) + '\n', encoding='utf-8')


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument('--class', dest='sample_class', default='heap',
                    choices=['heap', 'uaf', 'fmt'])
    args = ap.parse_args()
    data = json.loads((EVAL / f'benchmark_summary_{args.sample_class}.json')
                      .read_text(encoding='utf-8'))
    out = EVAL / f'result_table_{args.sample_class}.tex'
    write_latex(data['tools'], out, args.sample_class)
    print('[latex] wrote', out)


if __name__ == '__main__':
    main()
